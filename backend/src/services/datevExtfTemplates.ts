let cachedReferenceSachkonten: Array<[string, string]> | null = null;

function loadReferenceSachkonten(): Array<[string, string]> {
  if (cachedReferenceSachkonten) return cachedReferenceSachkonten;
  const candidateDirs = [
    'C:/Users/sh/Desktop/Project - Dubai-20261103T125443Z-1-001/Project - Dubai/Accounting Project/Documents January - June 2026/CSVs',
    'C:/Users/sh/Desktop/Project - Dubai/Accounting Project/Documents January - June 2026/CSVs',
  ];
  for (const dir of candidateDirs) {
    try {
      if (fs.existsSync(dir)) {
        const files = fs.readdirSync(dir).filter((f) => f.startsWith('EXTF_Sachkonten_') && f.endsWith('.csv'));
        if (files.length > 0) {
          const content = fs.readFileSync(path.join(dir, files[0]), 'utf8');
          const lines = content.split(/\r?\n/).slice(2);
          const parsed: Array<[string, string]> = [];
          for (const line of lines) {
            if (!line.trim()) continue;
            const sep = line.includes(';') ? ';' : '\t';
            const parts = line.split(sep);
            if (parts.length >= 2) {
              const code = parts[0].replace(/^"|"$/g, '').trim();
              const label = parts[1].replace(/^"|"$/g, '').trim();
              if (code) parsed.push([code, label]);
            }
          }
          if (parsed.length > 100) {
            cachedReferenceSachkonten = parsed;
            return parsed;
          }
        }
      }
    } catch {
      // Ignore read errors and fall back to built-in list
    }
  }
  cachedReferenceSachkonten = OFFICIAL_SKR03_SACHKONTEN;
  return cachedReferenceSachkonten;
}

/**
 * Generates the complete EXTF_Sachkonten_<YYYYMMDD>_<HHMMSS>_<YEAR>.csv content
 * ensuring every Konto and Gegenkonto present in the bookings is included along with the official SKR03 chart.
 */
export function generateSachkontenCsvContent(
  bookings: BookingItem[],
  yearNum: number,
  timestamp17: string,
  getAccountDescription: (code: string) => string,
  mandantenNr = '710',
  beraterName = 'niazi'
): string {
  const line1 = `"EXTF";700;20;"Kontenbeschriftungen";2;${timestamp17};;"AG";"${beraterName}";;1;${mandantenNr};${yearNum}0101;4;;;;;;;;;;;;;;;`;
  const line2 = `"Konto";"Kontobeschriftung";"SprachId";"Kontenbeschriftung lang"`;

  const accountMap = new Map<string, string>();
  for (const [code, label] of loadReferenceSachkonten()) {
    accountMap.set(code, label);
  }
  for (const [code, label] of OFFICIAL_SKR03_SACHKONTEN) {
    if (!accountMap.has(code)) {
      accountMap.set(code, label);
    }
  }

  // Ensure every account referenced in the bookings is present in Sachkonten
  for (const b of bookings) {
    if (b.konto && !accountMap.has(b.konto)) {
      accountMap.set(b.konto, getAccountDescription(b.konto));
    }
    if (b.gegenkonto && !accountMap.has(b.gegenkonto)) {
      accountMap.set(b.gegenkonto, getAccountDescription(b.gegenkonto));
    }
  }

  const rows: string[] = [];
  for (const [konto, label] of accountMap.entries()) {
    const cleanLabel = label.replace(/[;"\r\n]/g, '').trim().substring(0, 40);
    rows.push(`${konto};"${cleanLabel}";"de-DE";""`);
  }

  return '\uFEFF' + [line1, line2, ...rows].join('\r\n') + '\r\n';
}

